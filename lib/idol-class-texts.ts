/**
 * 抽一段这节课的固定文本：从该课程的 5 段里随机抽，避免连续两次抽中同一段。
 * lastId 是上一节这门课抽到的文本 id；不传就是第一次抽。
 */
export function pickClassText(key: string, lastId?: string): ClassText | null {
  const pool = CLASS_TEXTS[key];
  if (!pool?.length) return null;
  const candidates = lastId ? pool.filter(t => t.id !== lastId) : pool;
  const list = candidates.length ? candidates : pool;
  return list[Math.floor(Math.random() * list.length)];
}
