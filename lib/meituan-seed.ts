export function seedShops(): MtShop[] {
    const now = new Date().toISOString();
    return SHOPS.map(([name, cat, emoji, rating, monthly, perCapita, eta, distance, minOrder, deliveryFee, tags, desc, address, dishes, reviews]) => ({
        id: mtId("shop"),
        name, cat, emoji, rating, monthly, perCapita, eta, distance, minOrder, deliveryFee, tags, desc, address,
        dishes: dishes.map(([group, n, d, price, m, e]): MtDish => ({ id: mtId("dish"), group, name: n, desc: d, price, monthly: m, emoji: e })),
        reviews: reviews.map(([n, stars, text], i): MtReview => ({ id: mtId("rv"), name: n, stars, text, taste: stars, pack: Math.min(5, stars + 1), at: new Date(Date.now() - (i + 1) * 3 * 86400_000).toISOString() })),
        reviewCount: Math.round(monthly * 0.6),
        source: "home",
        createdAt: now,
    }));
}

export function seedDeals(): MtDeal[] {
    return DEALS.map(([shopName, title, kind, emoji, price, origin, rating, sold, desc]) => ({ id: mtId("deal"), shopName, title, kind, emoji, price, origin, rating, sold, desc }));
}
