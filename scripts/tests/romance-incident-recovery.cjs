const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
if (!process.argv[2]) throw new Error('Pass a local KV fixture JSON; never commit personal save fixtures.');
const fixture = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const entries = new Map(Object.entries(fixture));
entries.set('desktop-sentinel', 'unchanged');
const original = new Map(entries);
const cache = new Map();
function load(name) {
  if (name === './kv-db') return { kvGet: k => entries.get(k) ?? null, kvSet: (k,v) => entries.set(k,v), isKvHydrated: () => true };
  if (cache.has(name)) return cache.get(name);
  const exports = {};
  const file = path.join(__dirname, '../../lib', name + '.ts');
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  vm.runInNewContext(code, { exports, require: load, Date, console });
  cache.set(name, exports);
  return exports;
}
const storage = load('./idol-romance-storage');
