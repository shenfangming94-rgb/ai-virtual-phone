assert.equal(restored.lines.heir.doneNodes.join(','), 'busking_meet,company_contrast');
assert.equal(restored.lines.trainee.doneNodes.join(','), 'han_river_ramen');
assert.equal(restored.lines.underground.nextNode, 'song_for_her');
assert.equal(restored.lines.trainee.nextNode, 'collab_stage');
for (const [key, value] of original) assert.equal(entries.get(key), value, `unrelated/original key changed: ${key}`);
assert.equal(entries.size, original.size + 2);
restored.lines.underground.bond = 56;
storage.writeRomanceRoutes(restored);
entries.set('idol_romance_v1', JSON.stringify({ knowledge: [], exposures: [] }));
assert.equal(storage.readRomanceRoutes().lines.underground.bond, 56, 'repair must not replay');
