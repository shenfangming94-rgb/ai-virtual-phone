const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/theqoo-model.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exportsObject });
const { emptyForum, publishForum } = exportsObject;
const source = { eventId: 'calendar:event:1', revision: 1, publicAt: 100, title: '公开预告', publicFacts: ['官方宣布下周举行演出，尚未举行'], phase: 'announced', board: 'idol', hot: true, notify: true };
const draft = { title: { ko: '공개 일정', zh: '公开日程' }, body: [{ ko: '기대된다', zh: '期待' }], comments: [{ ko: '언제?', zh: '什么时候？', likes: 2 }], views: 10, recommendations: 3 };
let s = publishForum(emptyForum(), source, draft, 'initial', 100);
assert.equal(s.posts.length, 1);
assert.equal(publishForum(s, source, draft, 'initial', 100), s, 'retry is a no-op');
s.posts[0].liked = true;
const original = JSON.stringify(s.posts[0].comments[0]);
s = publishForum(s, source, draft, 'conversation:2', 110);
assert.equal(s.posts[0].comments.length, 2);
assert.equal(s.posts[0].updates.length, 0);
assert.equal(s.posts[0].liked, true);
assert.throws(() => publishForum(s, { ...source, publicFacts: ['new secret fact'] }, draft, 'bad', 110), /同一阶段/);
assert.throws(() => publishForum(s, { ...source, publicAt: 200 }, draft, 'future', 110), /已公开/);
const advance = { ...source, revision: 2, publicAt: 120, phase: 'update', publicFacts: [...source.publicFacts, '官方更新了时间'] };
s = publishForum(s, advance, draft, 'public:2', 120);
assert.equal(s.posts.length, 1);
assert.equal(s.posts[0].updates.length, 1);
assert.equal(s.posts[0].comments[2].revision, 2);
assert.equal(JSON.stringify(s.posts[0].comments[0]), original, 'old comments stay immutable');
assert.throws(() => publishForum(s, source, draft, 'stale', 130), /旧进展/);
assert.throws(() => publishForum(emptyForum(), source, { ...draft, title: { ko: 'title', zh: '' } }, 'invalid', 100), /格式/);
assert.throws(() => publishForum(emptyForum(), { ...source, images: [{ src: 'javascript:alert(1)', caption: '' }] }, draft, 'unsafe', 100), /图片/);
assert.equal(JSON.parse(JSON.stringify(s)).posts[0].liked, true);
console.log('PASS: deduplication, public timing, same-stage fact freeze, append-only updates, stale revisions, bilingual validation, image validation, persisted likes.');
